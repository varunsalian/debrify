/// The league with [id], or null when unknown.
SportsLeague? sportsLeagueById(String id) {
  for (final league in kSportsLeagues) {
    if (league.id == id) return league;
  }
  return null;
}

/// Importance of the league with [id]; 0 when unknown.
int sportsLeagueImportance(String id) => sportsLeagueById(id)?.importance ?? 0;

/// How cards of [league] are laid out on the board.
SportsEventShape sportsEventShapeOf(SportsLeague league) =>
    switch (league.sport) {
      SportKind.cricket => SportsEventShape.innings,
      SportKind.tennis => SportsEventShape.sets,
      SportKind.combat => SportsEventShape.card,
      SportKind.golf || SportKind.motorsport => SportsEventShape.event,
      _ => SportsEventShape.teams,
    };
