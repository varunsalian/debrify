#!/usr/bin/env python3
"""Prove original declaration coverage and report private dependency ownership.

Local only: the historical source is read from 072407c3. --write-report
regenerates the checked-in report after an intentional map correction.
"""
import sys
from storage_dart import ROOT, code_tokens, members, original, read_map

REPORT = ROOT / 'dev/tool/storage_dependencies.txt'


def report():
    ms, rows = members(original()), read_map()
    mapping = {r['member']: r for r in rows}
    expected = {m.name for m in ms} | {'AmbientTrailerSurface', 'TvRenderQuality', 'ApiKeyValidator'}
    assert len(ms) == 1078
    assert len(mapping) == len(rows) == 1081
    assert set(mapping) == expected, (expected-set(mapping), set(mapping)-expected)
    for m in ms:
        r = mapping[m.name]
        assert r['ref_kind'] == 'static'
        assert r['kind'] == ('reset_entry' if m.name == 'resetProfileCaches' else m.kind)
        assert 1 <= r['step'] <= 8 and r['shared'] in ('yes', 'no')
        if r['shared'] == 'yes':
            assert m.name.startswith('_') and m.kind in ('method', 'key', 'const')
            promoted = m.name[1:]
            if promoted in expected:
                promoted += 'Internal'
            assert r['target'].endswith('.'+promoted)
    uses = {m.name: {t.text for t in code_tokens(m.declaration)} for m in ms}
    lines = [
        'StorageService private dependency report (072407c3)',
        'Generated by python3 dev/tool/check_storage_map.py --write-report.',
        'Coverage: 1,078 static members + 2 enums + ApiKeyValidator = 1,081 rows.',
        'Reset assignments are an independent partition, checked by check_storage_bodies.py;',
        'they do not require private state promotion. All other private uses appear below.',
        '',
    ]
    unresolved = []
    for m in ms:
        if not m.name.startswith('_'):
            continue
        r = mapping[m.name]
        users = [u.name for u in ms if u.name not in (m.name, 'resetProfileCaches')
                 and m.name in uses[u.name]]
        cross = [u for u in users if mapping[u]['file'] != r['file']
                 or mapping[u]['step'] != r['step']]
        if cross and r['shared'] != 'yes':
            unresolved.append(m.name)
        if cross and any(mapping[u]['step'] < r['step'] for u in cross):
            unresolved.append(m.name+' (consumer precedes declaration)')
        resolution = ('shared as '+r['target'] if r['shared'] == 'yes' else
                      'co-located' if users else 'retained, no internal consumers')
        lines.append(f"{m.name} -> {r['file']} (step {r['step']}); {resolution}")
        lines.append('  users: '+(', '.join(f"{u} [step {mapping[u]['step']}]" for u in users) or '(none)'))
    lines += ['', f'Unresolved: {len(unresolved)}', *unresolved]
    assert not unresolved, '\n'.join(unresolved)
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    generated = report()
    if '--write-report' in sys.argv:
        REPORT.write_text(generated)
    else:
        assert REPORT.read_text() == generated, 'Dependency report is stale'
    print('Storage member coverage: 1,081 rows; private dependencies: nothing unresolved.')
